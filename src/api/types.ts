/**
 * The shapes the BFF returns.
 *
 * Field names follow the IR and the Decision API exactly — `code` for a component, `ref` for a
 * flow step, `status` and `effectiveStatus` on an entity result. The back end, the vectors, the
 * audit trail and this file use one spelling, because two names for one thing is a bug waiting at
 * the boundary.
 */

/** A rule's lifecycle status, as the repository shows it. */
export type RuleStatus = 'live' | 'in_review' | 'draft' | 'superseded';

/** A component outcome (00 §3.5). */
export type Outcome =
  | 'PASS'
  | 'DEVIATION'
  | 'REFER'
  | 'FAIL'
  | 'NOT_APPLICABLE'
  | 'DATA_MISSING'
  | 'ERROR';

/** An overall decision (00 §3.5). */
export type Decision = 'APPROVE' | 'APPROVE_WITH_DEVIATION' | 'REFER' | 'DECLINE';

/** A row in the rule repository. */
export interface RuleSummary {
  readonly code: string;
  readonly name: string;
  /** The plain-language intent, shown under the name so a reviewer reads policy, not BEL. */
  readonly intent: string;
  readonly category: string;
  readonly productLines: readonly string[];
  readonly status: RuleStatus;
  readonly author: string;
  readonly lastModified: string;
  readonly version: number;
  /** How many earlier versions exist, for the expandable history. */
  readonly earlierVersions: number;
}

/** One entry in a rule's version history. */
export interface RuleVersion {
  readonly version: number;
  readonly status: RuleStatus;
  readonly author: string;
  readonly at: string;
  readonly note: string;
}

/** A submission awaiting review. */
export interface ReviewItem {
  readonly code: string;
  readonly name: string;
  readonly fromVersion: number;
  readonly toVersion: number;
  readonly category: string;
  readonly author: string;
  readonly submittedAt: string;
  readonly simulated: boolean;
  readonly testsPassed: number;
  readonly testsTotal: number;
  readonly changeSummary: string;
}

/** A simulation result. */
export interface SimulationResult {
  readonly applications: number;
  readonly pass: number;
  readonly deviation: number;
  readonly fail: number;
  readonly perRule: readonly {
    readonly code: string;
    readonly pass: number;
    readonly deviation: number;
    readonly fail: number;
  }[];
}

/** A decision in the explorer's recent list. */
export interface DecisionSummary {
  readonly decisionId: string;
  readonly applicationRef: string;
  readonly decision: Decision;
  readonly decidedAt: string;
  readonly latencyMs: number;
}

/** One rule's contribution to a decision, for the trace timeline. */
export interface TraceStep {
  readonly ref: string;
  readonly name: string;
  readonly status: Outcome;
  readonly effectiveStatus: Outcome;
  readonly reasonCode?: string;
  /** The condition that fired, rendered as policy prose rather than BEL. */
  readonly firedCondition?: string;
  readonly inputs?: Readonly<Record<string, string>>;
  readonly requiredLevel?: string;
  readonly annotation?: string;
}

/** A full decision trace (D7: regenerated by replay, not stored per rule). */
export interface DecisionTrace {
  readonly decisionId: string;
  readonly applicationRef: string;
  readonly decision: Decision;
  readonly stpEligible: boolean;
  readonly asOf: string;
  readonly policyCode: string;
  readonly policyVersion: number;
  /** The content hash of the bundle that decided it — the anchor a replay pins to (D5). */
  readonly bundleHash: string;
  readonly engineVersion: string;
  readonly steps: readonly TraceStep[];
}
